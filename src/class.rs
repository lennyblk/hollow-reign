    pub fn color(&self) -> Color {
        match self {
            Class::Knight => Color::Rgb { r: 80,  g: 140, b: 255 }, // bleu
            Class::Mage   => Color::Rgb { r: 255, g: 140, b: 30  }, // orange
            Class::Rogue  => Color::Rgb { r: 60,  g: 200, b: 80  }, // vert
        }
    }

    pub fn base_stats(&self) -> Stats {
        match self {
            Class::Knight => Stats {
                vigor: 14,
                intelligence: 9,
                faith: 9,
                dexterity: 13,
                arcane: 7,
                mind: 9,
                strength: 14,
            },
            Class::Mage => Stats {
                vigor: 9,
                intelligence: 20,
                faith: 7,
                dexterity: 12,
                arcane: 9,
                mind: 14,
                strength: 5,
            },
            Class::Rogue => Stats {
                vigor: 10,
                intelligence: 11,
                faith: 8,
                dexterity: 20,
                arcane: 11,
                mind: 11,
                strength: 10,
            },
        }
    }
